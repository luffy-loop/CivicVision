from functools import lru_cache
from io import BytesIO
from pathlib import Path
from PIL import Image, ImageStat, ImageOps
from fastapi import HTTPException
from app.core.config import get_settings

settings = get_settings()

def inspect_image(data: bytes) -> tuple[Image.Image, dict]:
    try:
        image = Image.open(BytesIO(data))
        width, height = image.size
        max_pixels = get_settings().max_image_pixels
        if width < 1 or height < 1 or width * height > max_pixels:
            raise HTTPException(status_code=413, detail=f"Image dimensions exceed the {max_pixels:,}-pixel processing limit.")
        image.verify()
        image = ImageOps.exif_transpose(Image.open(BytesIO(data))).convert("RGB")
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=400, detail="The uploaded file is not a valid supported image.") from exc
    width, height = image.size
    if width < 80 or height < 80:
        raise HTTPException(status_code=400, detail="Image is too small. Upload an image at least 80 × 80 pixels.")
    stats = ImageStat.Stat(image.convert("L"))
    mean = stats.mean[0]
    variance = stats.var[0]
    quality = {
        "too_dark": mean < 18,
        "too_bright": mean > 242,
        "low_contrast": variance < 80,
        "width": width,
        "height": height,
    }
    return image, quality

@lru_cache(maxsize=1)
def load_model():
    if not settings.model_path:
        return None
    path = Path(settings.model_path)
    if not path.is_file():
        raise RuntimeError(f"Configured MODEL_PATH does not exist: {path}")
    try:
        from ultralytics import YOLO
    except ImportError as exc:
        raise RuntimeError("MODEL_PATH is configured but Ultralytics is not installed. Install backend/requirements-ml.txt.") from exc
    return YOLO(str(path))

def predict(image: Image.Image) -> tuple[str, list[dict], str]:
    if not settings.model_path:
        if not settings.demo_mode:
            raise HTTPException(status_code=503, detail="No detector is configured. Set MODEL_PATH or enable demo mode.")
        # Intentionally no fabricated detections. Demo mode verifies the scan workflow only.
        return "demo", [], "Demo mode: no trained model is configured, so no road damage prediction was made."
    try:
        model = load_model()
        results = model.predict(image, verbose=False, conf=0.25)
        detections = []
        for result in results:
            names = result.names
            if result.boxes is None:
                continue
            for box in result.boxes:
                cls_id = int(box.cls.item())
                xyxy = [float(x) for x in box.xyxy[0].tolist()]
                detections.append({
                    "label": str(names.get(cls_id, cls_id)),
                    "confidence": float(box.conf.item()),
                    "box": xyxy,
                })
        return "model", detections, "Predictions generated by the configured model. Verify results before acting."
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=503, detail="The configured detector failed to run. Check model path, dependencies and server logs.") from exc
